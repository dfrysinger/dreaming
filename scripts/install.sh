  local label
  echo "halt=$([[ -e "$HALT_SWITCH" ]] && echo active || echo inactive)"
  [[ -f "$BACKUP_POINTER" ]] && echo "rollback_backup=$(<"$BACKUP_POINTER")"
  [[ -f "$GENERATION_FILE" ]] && echo "activation_generation=$(<"$GENERATION_FILE")"
