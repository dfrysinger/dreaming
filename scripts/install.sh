verify_backup() {
  /usr/bin/python3 - "$1" <<'PY'
import os
import plistlib
import sys
from pathlib import Path

backup = Path(sys.argv[1])
plists = sorted(backup.glob("*.plist"))
if not plists:
    raise SystemExit("backup contains no LaunchAgent plists")
failures = []
for plist in plists:
    try:
        data = plistlib.loads(plist.read_bytes())
    except Exception as exc:
        failures.append(f"{plist.name}: malformed plist: {exc}")
        continue
    arguments = data.get("ProgramArguments")
    if not isinstance(arguments, list) or not arguments or not all(
        isinstance(value, str) for value in arguments
    ):
        failures.append(f"{plist.name}: ProgramArguments must be a non-empty string array")
        continue
    for index, raw in enumerate(arguments):
        path = Path(os.path.expanduser(raw))
        if not path.is_absolute():
            continue
        must_execute = index == 0 or path.suffix in {".sh", ".py"} or os.access(path, os.X_OK)
        if must_execute and not (path.is_file() and os.access(path, os.X_OK)):
            failures.append(f"{plist.name}: executable missing or not executable: {path}")
        elif not must_execute and not path.exists():
            failures.append(f"{plist.name}: durable argument path is missing: {path}")
if failures:
    raise SystemExit("\n".join(failures))
PY
}

cmd_rollback() {
  local backup="${1:-}" label plist generation lock_path selftest_plist
  activate_halt
  if [[ -z "$backup" ]]; then
    [[ -f "$BACKUP_POINTER" ]] || {
      echo "no migration backup recorded" >&2
      return 1
    }
    backup="$(<"$BACKUP_POINTER")"
  fi
  [[ -d "$backup" && -f "$backup/.dreaming-backup-complete" ]] || {
    echo "invalid migration backup: $backup" >&2
    return 1
  }
  verify_backup "$backup"
  selftest_plist="$(find "$backup" -maxdepth 1 -type f -name '*.selftest.plist' -print)"
  [[ -n "$selftest_plist" && "$(printf '%s\n' "$selftest_plist" | wc -l | tr -d ' ')" == "1" ]] || {
    echo "rollback backup must contain exactly one selftest LaunchAgent" >&2
    return 1
  }
  attempt_unpublish

  while IFS= read -r label; do
    bootout_label "$label"
    rm -f "$DEST_DIR/$label.plist"
  done < <(all_labels | awk '!seen[$0]++')
  if [[ "$DREAMING_ENABLE_COPILOT_COMPAT" == "1" ]]; then
    "$DREAMING_REPO_ROOT/scripts/manage-instructions.sh" uninstall
  fi
  lock_path="$STATE_DIR/daemon.lock"
  if [[ -f "$lock_path" ]]; then
    mv "$lock_path" "$STATE_DIR/dreaming/daemon.lock.sqlite-before-rollback"
    [[ -f "${lock_path}-wal" ]] &&
      mv "${lock_path}-wal" "$STATE_DIR/dreaming/daemon.lock.sqlite-wal-before-rollback"
    [[ -f "${lock_path}-shm" ]] &&
      mv "${lock_path}-shm" "$STATE_DIR/dreaming/daemon.lock.sqlite-shm-before-rollback"
  fi
  for plist in "$backup"/*.plist; do
    [[ -e "$plist" ]] || continue
    cp -p "$plist" "$DEST_DIR/"
    label="$(basename "$plist" .plist)"
    "$LAUNCHCTL" bootstrap "$DOMAIN" "$DEST_DIR/$label.plist"
    "$LAUNCHCTL" enable "$DOMAIN/$label" >/dev/null 2>&1 || true
    echo "restored $label"
  done
  generation="$(date -u +%Y%m%dT%H%M%SZ)-rollback-$$"
  atomic_pointer "$generation" "$GENERATION_FILE"
  atomic_pointer "$(basename "$selftest_plist" .plist)" "$SELFTEST_LABEL_FILE"
  rm -f "$SELFTEST_GENERATION_FILE"
  if [[ "$PUBLICATION_RESIDUAL" == "1" ]]; then
    echo "rollback loaded behind halt from $backup; publication residuals remain; run restored selftest, then enable explicitly"
  else
    echo "rollback loaded behind halt from $backup; run restored selftest, then enable explicitly"
  fi
}

cmd_rollback_migration() {
  local journal="$DREAMING_STATE_DIR/copilot-migration.json"
  activate_halt
  [[ -f "$journal" ]] || {
    echo "no Copilot migration journal recorded: $journal" >&2
    return 1
  }
  "$DREAMING_REPO_ROOT/scripts/migrate-copilot-state.py" rollback \
    --legacy-skills "${DREAMING_LEGACY_COPILOT_SKILLS:-$HOME/.copilot/skills}" \
    --legacy-state "${DREAMING_LEGACY_COPILOT_STATE:-$HOME/.copilot/skill-state/skill-review}" \
    --target-skills "$DREAMING_SKILLS_ROOT" \
    --target-state "$DREAMING_STATE_DIR" \
    --journal "$journal"
  echo "migration data rolled back; halt remains active"
}

run_with_lifecycle_lock() {
  mkdir -p "$(dirname "$LIFECYCLE_LOCK_FILE")"
  exec /usr/bin/python3 - "$LIFECYCLE_LOCK_FILE" "$0" "$@" <<'PY'
import fcntl
import os
import subprocess
import sys

lock_path, script, *args = sys.argv[1:]
with open(lock_path, "a+") as lock:
    os.chmod(lock_path, 0o600)
    fcntl.flock(lock, fcntl.LOCK_EX)
    env = os.environ.copy()
    env["DREAMING_LIFECYCLE_LOCK_HELD"] = "1"
    raise SystemExit(subprocess.run([script, *args], env=env).returncode)
PY
}

if [[ "${DREAMING_LIFECYCLE_LOCK_HELD:-0}" != "1" ]]; then
  case "${1:-}" in
    prepare|install|selftest|enable|uninstall|rollback|rollback-migration)
      run_with_lifecycle_lock "$@"
      ;;
  esac
fi

case "${1:-}" in
  prepare) cmd_prepare ;;
  install) cmd_install ;;
  selftest) cmd_selftest ;;
  enable) cmd_enable ;;
  status) cmd_status ;;
  dashboard-url) cmd_dashboard_url ;;
  dashboard-open) cmd_dashboard_open ;;
  uninstall) cmd_uninstall ;;
  rollback) shift; cmd_rollback "${1:-}" ;;
  rollback-migration) cmd_rollback_migration ;;
  *)
    echo "usage: scripts/install.sh {prepare|install|selftest|enable|status|dashboard-url|dashboard-open|uninstall|rollback [backup]|rollback-migration}" >&2
    exit 2
    ;;
esac
